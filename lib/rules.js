const RULES_FILE = join(PLUGIN_HOME, 'rules.md');

/** 读规则：有 rules.md 就用文件，否则用默认 */
export function qqRulesText() {
    try {
        const text = fs.readFileSync(RULES_FILE, 'utf8').trim();
        if (text) return text;
    } catch {
        // 没有文件就是默认，属正常状态
    }
    return QQ_RULES_DEFAULT;
}

export { RULES_FILE };
